#include <string>
#include <vector>

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

void min_of_two() {
    int a = 33, b = 57;
    int m = (a < b) ? a : b;
    (void)m;
}

void char_frequency() {
    std::string text = "banana";
    int count = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == 'a') count += 1;
    }
    (void)count;
}

extern "C" int ivory_meadow();
extern "C" void frost_crescent();
extern "C" void frost_summit();
extern "C" void radiant_crescent();

int main() {
    collect_triples();
    gcd_triple();
    min_of_two();
    char_frequency();
    frost_crescent();
    frost_summit();
    radiant_crescent();
    return ivory_meadow();
}
